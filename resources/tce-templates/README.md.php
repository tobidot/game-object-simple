## Commands

```bash
npm install        # once
npm start          # dev harness (index.html) with live reload
npm run check      # tsc + eslint — the mechanically enforced part of the coding standard
npm run build      # dist/index.js (ES module) + dist/index.global.js (IIFE)
npm run pack       # build, then zip dist/ into release/<?= $config->name ?>-<version>.zip
```

## Layout

- `src/index.ts` — the entry point: binds the package into the page's loader (`TceRoot.bind_self`)
  and initializes it. Every package script does exactly this, so the zero-script embed works.
<?php if ($config->kind === 'library'): ?>
- `src/<?= $config->className ?>.ts` — the library: exposed functions, their per-function contracts,
  and zod schemas for every argument.
<?php elseif ($config->template === 'minimal'): ?>
- `src/<?= $config->className ?>.ts` — the element, small enough to stay one class.
- `src/applet.scss` — its styles (BEM, scoped to the shadow root).
<?php else: ?>
- `src/<?= $config->className ?>.ts` — the element, a shallow delegate wiring together
  `Settings` (constants), `References` (DOM, built once), `Properties` (state),
  `Renderer` (pure painting) and `Logic` (every decision) — see *Coding Style: Splitting a
  Non-Trivial Class*.
- `src/applet.scss` — its styles (BEM, scoped to the shadow root).
<?php endif; ?>
<?php if ($config->libraryDependencies() !== []): ?>
- `src/contracts/` — the vendored contracts of the libraries this package calls; assert each
  function with `assert_contract` in `init()` (*Interfacing Between Elements*).
<?php endif; ?>
- `public/` (create it when needed) — static assets, copied into `dist/` and resolved with
  `resolve_asset_url` (*Assets & Build*).
- `vendor/` — the SDK packages this project was generated against (`<?= implode(', ', array_map(fn (array $sdk) => "{$sdk['npm_name']}@{$sdk['version']}", $config->sdk)) ?>`),
  referenced from `package.json` as `file:` dependencies. Replace them with newer copies to upgrade.
- `tobidot-project.json` — the project manifest (*The tobidot-project.json Manifest*).
- `icon.svg` — 64×64 desktop icon in the house palette (*Styling Guide*).

## Publishing

`npm run pack` writes `release/<?= $config->name ?>-<?= $config->version ?>.zip`. Upload it to the registry:

```bash
curl -X POST <?= $config->siteUrl ?>/api/v1/tce-packages \
  -H "Authorization: Bearer $TOKEN" \
  -F namespace=<?= $config->namespace ?> -F name=<?= $config->name ?> -F kind=<?= $config->kind ?> \
  -F version=<?= $config->version ?> -F width=<?= $config->width ?> -F height=<?= $config->height ?> \
  -F "description=<?= str_replace('"', '\"', $config->description) ?>" \
  -F icon=@<?= $config->iconFileName ?> \
<?php foreach ($config->dependencies as $index => $dependency): ?>
  -F "dependencies[<?= $index ?>][namespace]=<?= $dependency['namespace'] ?>" -F "dependencies[<?= $index ?>][name]=<?= $dependency['name'] ?>" \
<?php endforeach; ?>
  -F zip=@release/<?= $config->name ?>-<?= $config->version ?>.zip
```

Afterwards it is embeddable anywhere with one script tag and one HTML tag
(*Integration Into Websites*):

```html
<?php foreach ($config->dependencies as $dependency): ?>
<script src="<?= $config->siteUrl ?>/tce-elements/<?= $dependency['namespace'] ?>/<?= $dependency['name'] ?>"></script>
<?php endforeach; ?>
<script src="<?= $config->siteUrl ?>/tce-elements/<?= $config->namespace ?>/<?= $config->name ?>"></script>
<?php if ($config->kind === 'element'): ?>
<<?= $config->name ?>></<?= $config->name ?>>
<?php endif; ?>
```
